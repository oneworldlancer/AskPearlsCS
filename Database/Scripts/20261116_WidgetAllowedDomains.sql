IF OBJECT_ID(N'dbo.ASKPEARLS_WIDGET_ALLOWED_DOMAIN_LIST', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.ASKPEARLS_WIDGET_ALLOWED_DOMAIN_LIST
    (
        Id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_ASKPEARLS_WIDGET_ALLOWED_DOMAIN_LIST PRIMARY KEY,
        RowTokenId UNIQUEIDENTIFIER NOT NULL CONSTRAINT DF_AP_DOMAIN_RowTokenId DEFAULT NEWID(),
        WidgetPublicKey NVARCHAR(200) NOT NULL,
        OwnerUserTokenId NVARCHAR(200) NOT NULL,
        NormalizedDomain NVARCHAR(253) NOT NULL,
        CreatedAtUtc DATETIME2(3) NOT NULL CONSTRAINT DF_AP_DOMAIN_Created DEFAULT SYSUTCDATETIME(),
        CONSTRAINT UQ_AP_WIDGET_ALLOWED_DOMAIN UNIQUE (WidgetPublicKey, NormalizedDomain)
    );
